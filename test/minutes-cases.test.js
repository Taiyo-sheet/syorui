'use strict';
/*
 * かんたん整理（AIなしの整理）の、精度の確認。いろいろな話し方の例文で、項目ごとに、正しく分かれたかを数える。
 * ※ 例文は、開発者が作ったもの。実際の文字起こしで、試して、ここに足していく（精度の基準：全体で 90% 以上）
 */
const test = require('node:test');
const assert = require('node:assert');
const lib = require('../customize/doc-button.js');

// expect：項目ごとに、含まれていてほしい言葉（配列）。none：その項目に、入ってほしくない言葉
const CASES = [
  { name: '見出しを言う', t: '出席者は、太田さんと國井さんです。場所は、現場事務所です。議題は、夜間規制の時間です。決まったことは、規制は9時から17時です。宿題は、10月25日までに太田さんが見積書を出します。次回は、11月1日です。',
    expect: { 出席者: ['太田', '國井'], 場所: ['現場事務所'], 議題: ['夜間規制'], 決定事項: ['9時から17時'], ToDo: ['10/25', '太田', '見積書'], 次回予定: ['11月1日'] } },
  { name: 'ふつうの話し方A', t: '今日は現場事務所で、太田さん、國井さん、元請の藤原さんが出席して打合せをしました。夜間規制の時間について確認しました。9時から17時で調整することになりました。藤原さんは近隣への周知をお願いします。次回は11月1日です。',
    expect: { 出席者: ['太田', '國井', '藤原（元請）'], 場所: ['現場事務所'], 議題: ['夜間規制'], 決定事項: ['9時から17時'], ToDo: ['藤原', '近隣'], 次回予定: ['11月1日'] } },
  { name: 'ふつうの話し方B（オンライン）', t: 'えー、本日はオンラインで、山田さんと鈴木さんが参加しました。工程表の見直しについて話し合いました。着工は11月上旬ということで合意しました。10月30日までに山田さんが工程表を共有します。',
    expect: { 出席者: ['山田', '鈴木'], 場所: ['オンライン'], 議題: ['工程表'], 決定事項: ['11月上旬'], ToDo: ['10/30', '山田', '工程表'] } },
  { name: '期限が、来週・明日', t: '来週までに太田さんが見積書を出します。明日までに國井さんが図面を送ります。',
    expect: { ToDo: ['来週｜太田｜見積書', '明日｜國井｜図面'] } },
  { name: '期限が、月末・日にち', t: '月末までに鈴木さんが請求書を発行します。25日までに山田さんが材料を手配します。',
    expect: { ToDo: ['月末｜鈴木｜請求書', '25日｜山田｜材料'] } },
  { name: '議題を、本日の議題は', t: '本日の議題は、工程の確認、材料の発注です。',
    expect: { 議題: ['工程の確認', '材料の発注'] } },
  { name: '決定の言い回しいろいろ', t: '施工は11月5日からで進めます。材料はAタイプを採用します。作業時間は夜間でいきます。',
    expect: { 決定事項: ['11月5日', 'Aタイプ', '夜間'] } },
  { name: '次回の言い方', t: '次の打合せは、11月8日の午前10時です。',
    expect: { 次回予定: ['11月8日'] } },
  { name: 'フィラーが多い', t: 'えーっと、あの、場所は、現場事務所です。まあ、出席者は、太田さんと國井さんです。',
    expect: { 場所: ['現場事務所'], 出席者: ['太田', '國井'] } },
  { name: '内容は、メモに残る', t: '現場は雪が多いそうです。近隣から騒音の苦情がありました。',
    expect: { 議事録メモ: ['雪が多い', '苦情'] } },
];

test('かんたん整理：いろいろな話し方の例文で、項目ごとの精度（90%以上）', () => {
  let total = 0, ok = 0; const miss = [];
  CASES.forEach((c) => {
    const r = lib.summarizeLocal(c.t);
    Object.keys(c.expect).forEach((k) => c.expect[k].forEach((w) => { total++; if (String(r[k] || '').includes(w)) ok++; else miss.push(c.name + '／' + k + '：「' + w + '」が無い（実際：' + JSON.stringify(r[k]) + '）'); }));
  });
  const pct = Math.round((ok / total) * 100);
  console.log('かんたん整理の精度：' + ok + '/' + total + '（' + pct + '%）' + (miss.length ? '\n  ' + miss.join('\n  ') : ''));
  assert.ok(pct >= 90, '精度が 90% を下回りました：' + pct + '%\n' + miss.join('\n'));
});
